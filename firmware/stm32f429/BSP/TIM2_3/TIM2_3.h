#ifndef __TIM2_3_H
#define __TIM2_3_H

#include "stm32f4xx.h"

/* ════════════════════════════════════════════════════════════
 *  TIM2 — 优先级 4（线上，BASEPRI=5 拦不住）
 *  TIM3 — 优先级 6（线下，BASEPRI=5 拦住）
 *
 *  两个通用定时器当基本定时器用（只计数+中断，不输出引脚）。
 *  周期 1s：90MHz / 9000 / 10000 = 1Hz
 *
 *  关中断时 TIM2 照打印、TIM3 暂停——验证 BASEPRI 分界线。
 * ════════════════════════════════════════════════════════════ */
#define TIM2_3_PSC  9000-1       /* 90MHz / 9000 = 10KHz             */
#define TIM2_3_ARR  10000-1      /* 10KHz / 10000 = 1Hz = 1s         */

void TIM2_3_Init(void);          /* 一次性初始化 TIM2 + TIM3          */

#endif
